'use strict';
const {test,expect}=require('@playwright/test');
const ORIGIN='http://127.0.0.1:8765';
for(const theme of ['veyra','oryn','nilo','ember','verdant','pearl'])test('Applications guide works without saving cases in '+theme,async({page})=>{
 const external=[];
 await page.route('**/*',route=>{
  if(new URL(route.request().url()).origin===ORIGIN)return route.continue();
  external.push(route.request().url());return route.abort();
 });
 await page.goto(ORIGIN+'/');
 await page.getByLabel('Workspace theme').selectOption(theme);
 await page.locator('[data-workspace="applications"]').click();
 await expect(page.locator('#applications-workflow')).toBeVisible();
 await expect(page.locator('#listings-workflow')).toBeHidden();
 await expect(page.locator('#future-workflow')).toBeHidden();
 await page.locator('#applications-workflow').getByRole('button',{name:'Build prompt',exact:true}).click();await page.locator('#applications-workflow').getByRole('button',{name:'View all',exact:true}).click();
 await page.locator('#application-property').fill('100 Fictional Drive, Unit 3');
 await page.locator('#application-status').fill('Authorization not yet received');
 await page.locator('#application-request').fill('What should the staff do next?');
 await expect(page.locator('#application-guide-prompt')).toHaveValue(/100 Fictional Drive, Unit 3/);
 await expect(page.locator('#application-guide-prompt')).toHaveValue(/Authorization not yet received/);
 await expect(page.locator('#application-guide-prompt')).toHaveValue(/Next Action/);
 await page.locator('#application-rent').fill('1000');
 await page.locator('#application-grossPay').fill('1500');
 await page.locator('#application-payFrequency').selectOption('biweekly');
 await expect(page.locator('#application-income-result')).toContainText('$3250.00');
 await expect(page.locator('#application-income-result')).toContainText('$3000.00');
 await page.locator('#application-mode').selectOption('income');
 await expect(page.locator('#application-guide-prompt')).toHaveValue(/Income Worksheet/);
 await page.locator('#application-mode').selectOption('summary');
 await expect(page.locator('#application-guide-prompt')).toHaveValue(/APPLICATION REVIEW SUMMARY/);
 await page.context().grantPermissions(['clipboard-read','clipboard-write']);
 await page.locator('#application-guide-copy').click();
 expect(await page.evaluate(()=>navigator.clipboard.readText())).toBe(await page.locator('#application-guide-prompt').inputValue());
 await page.locator('#application-mode').selectOption('draft');
 await expect(page.locator('#application-guide-prompt')).toHaveValue(/Suggested Draft/);
 await page.locator('#application-mode').selectOption('capture');
 await expect(page.locator('#application-guide-prompt')).toHaveValue(/Confirmed Step Sequence/);
 await page.setViewportSize({width:390,height:850});
 await expect.poll(()=>page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
 await page.locator('[data-workspace="listings"]').click();await expect(page.locator('#listings-workflow')).toBeVisible();
 await page.locator('[data-workspace="applications"]').click();await expect(page.locator('#application-status')).toHaveValue('Authorization not yet received');
 await page.locator('#application-guide-clear').click();
 await expect(page.locator('#application-status')).toHaveValue('');
 await expect(page.locator('#application-mode')).toHaveValue('next');
 await page.reload();await page.locator('[data-workspace="applications"]').click();
 await expect(page.locator('#application-property')).toHaveValue('');
 await expect(page.locator('#application-status')).toHaveValue('');
 expect(external).toEqual([]);
 await expect(page.getByLabel('Workspace theme')).toHaveValue(theme);
});
